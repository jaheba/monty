"""Regenerate the experimental fusion registry and VM handlers."""

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
loads = [f'LoadLocal{i}' for i in range(4)] + ['LoadLocal']
methods = {
    'BinaryAdd': 'binary_add',
    'BinarySub': 'binary_sub',
    'BinaryMul': 'binary_mult',
    'BinaryFloorDiv': 'binary_floordiv',
    'BinaryMod': 'binary_mod',
    'BinaryAnd': 'binary_and',
    'BinaryOr': 'binary_or',
    'BinaryXor': 'binary_xor',
    'CompareEq': 'compare_eq',
    'CompareNe': 'compare_ne',
    'CompareLt': 'compare_lt',
    'CompareLe': 'compare_le',
    'CompareGt': 'compare_gt',
    'CompareGe': 'compare_ge',
    'InplaceAdd': 'inplace_add',
    'InplaceSub': 'inplace_sub',
}
patterns = []
for a in loads:
    for b in loads:
        patterns.append((a, b))
for a in loads:
    for op in ['BinaryAdd', 'BinarySub', 'BinaryMul', 'BinaryMod', 'CompareLt']:
        patterns.append((a, 'LoadSmallInt', op))
for a, b in [('LoadLocal0', 'LoadLocal1'), ('LoadLocal1', 'LoadLocal2'), ('LoadLocal', 'LoadLocal')]:
    for op in ['BinaryAdd', 'BinarySub', 'BinaryMul', 'BinaryFloorDiv', 'BinaryMod', 'CompareLt', 'BinarySubscr']:
        patterns.append((a, b, op))
for a in loads:
    for op in ['BinaryAdd', 'BinaryMul', 'InplaceAdd', 'InplaceSub']:
        patterns.append((a, op))
for op in ['BinaryAdd', 'BinarySub', 'BinaryMul', 'BinaryMod', 'InplaceAdd', 'InplaceSub']:
    patterns.append((op, 'StoreLocal'))
for op in ['CompareEq', 'CompareNe', 'CompareLt', 'CompareLe', 'CompareGt', 'CompareGe']:
    for jump in ['JumpIfTrue', 'JumpIfFalse']:
        patterns.append((op, jump))
patterns += [('StoreLocal', 'StoreLocal'), ('LoadSmallInt', 'StoreLocal'), ('LoadLocal', 'StoreLocal')]
assert len(patterns) == len(set(patterns))
assert 127 + len(patterns) <= 256
names = ['Fused' + ''.join(p) for p in patterns]

p = ROOT / 'crates/monty/src/bytecode/op.rs'
s = p.read_text()
start = '    // BEGIN GENERATED FUSIONS\n'
end = '    // END GENERATED FUSIONS\n'
if start in s:
    s = s[: s.index(start)] + s[s.index(end) + len(end) :]
block = start
for i, name in enumerate(names, 127):
    block += f'    #[cfg(feature = "experimental-fusion")]\n    {name} = {i},\n'
block += end
s = s.replace('    YieldFrom = 126,\n', '    YieldFrom = 126,\n' + block)
start2 = '            // BEGIN GENERATED FUSION SHAPES\n'
end2 = '            // END GENERATED FUSION SHAPES\n'
if start2 in s:
    s = s[: s.index(start2)] + s[s.index(end2) + len(end2) :]
block = start2 + '            #[cfg(feature = "experimental-fusion")]\n'
block += '            ' + '\n            | '.join('Self::' + n for n in names) + ' => OperandShape::None,\n' + end2
s = s.replace(
    '    fn operand_shape(self) -> OperandShape {\n        match self {',
    '    fn operand_shape(self) -> OperandShape {\n        match self {\n' + block,
)
p.write_text(s)

registry = '//! Generated by crates/monty-bench/experiments/fused-ops/generate.py.\n\nuse super::op::Opcode;\n\n'
registry += 'const PATTERNS: &[(Opcode, &[Opcode])] = &[\n'
for name, ops in zip(names, patterns):
    registry += '    (Opcode::' + name + ', &[' + ', '.join('Opcode::' + o for o in ops) + ']),\n'
registry += """];

#[cfg(test)]
use std::cell::RefCell;

#[cfg(test)]
thread_local! {
    static CENSUS: RefCell<(usize, [usize; 112])> = const { RefCell::new((0, [0; 112])) };
}

/// Replace only the first opcode; retained bytes keep all original offsets valid.
pub(super) fn fuse(bytecode: &mut [u8], offsets: &[usize]) {
    #[cfg(test)]
    CENSUS.with_borrow_mut(|stats| stats.0 += offsets.len());
    let mut index = 0;
    while index < offsets.len() {
        let best = PATTERNS.iter().filter(|(_, ops)| {
            index + ops.len() <= offsets.len()
                && ops.iter().enumerate().all(|(i, op)| bytecode[offsets[index + i]] == *op as u8)
        }).max_by_key(|(_, ops)| ops.len());
        if let Some((fused, ops)) = best {
            #[cfg(test)]
            CENSUS.with_borrow_mut(|stats| stats.1[*fused as usize - 127] += 1);
            bytecode[offsets[index]] = *fused as u8;
            index += ops.len();
        } else {
            index += 1;
        }
    }
}
"""
registry += """
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    #[ignore = "prints static fusion coverage for the benchmark workloads"]
    fn workload_fusion_census() {
        use std::{fs, path::Path};

        use monty_types::CompileOptions;

        use crate::MontyRun;

        let root = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../monty-bench/experiments/fused-ops/workloads");
        let mut paths: Vec<_> = fs::read_dir(root).unwrap()
            .map(|entry| entry.unwrap().path()).collect();
        paths.sort();
        println!("case,instructions,fused_sites,eliminated_dispatches");
        for path in paths {
            CENSUS.with_borrow_mut(|stats| *stats = (0, [0; 112]));
            let runner = MontyRun::new(fs::read_to_string(&path).unwrap(), "bench.py", vec![],
                CompileOptions::default()).unwrap();
            drop(runner);
            CENSUS.with_borrow(|(instructions, counts)| {
                let sites: usize = counts.iter().sum();
                let eliminated: usize = counts.iter().zip(PATTERNS)
                    .map(|(count, (_, ops))| count * (ops.len() - 1)).sum();
                println!("{},{instructions},{sites},{eliminated}",
                    path.file_stem().unwrap().to_str().unwrap());
            });
        }
    }

    #[test]
    fn every_pattern_preserves_operands_and_interior_entry_points() {
        for (fused, ops) in PATTERNS {
            let mut bytes = Vec::new();
            let mut offsets = Vec::new();
            for op in *ops {
                offsets.push(bytes.len());
                bytes.push(*op as u8);
                match op {
                    Opcode::LoadLocal | Opcode::LoadSmallInt | Opcode::StoreLocal => bytes.push(9),
                    Opcode::JumpIfTrue | Opcode::JumpIfFalse => bytes.extend([0, 0]),
                    _ => {}
                }
            }
            let original = bytes.clone();
            fuse(&mut bytes, &offsets);
            assert_eq!(bytes[0], *fused as u8);
            assert_eq!(bytes[1..], original[1..]);
        }
    }
}
"""
(ROOT / 'crates/monty/src/bytecode/fused.rs').write_text(registry)

vm = '//! Generated by crates/monty-bench/experiments/fused-ops/generate.py.\n\nuse super::{PyTrait, RunResult, VM, Value};\n\n#[expect(clippy::inline_always, reason = "Fusion must avoid an additional call per dispatch.")]\nimpl VM<\'_> {\n'
for idx, (name, ops) in enumerate(zip(names, patterns)):
    vm += f'    #[inline(always)]\n    pub(super) fn fused_{idx}(&mut self, countdown: &mut u8, check_limits: bool, poll_print: bool) -> RunResult<()> {{\n'
    for i, op in enumerate(ops):
        if i:
            vm += """        self.fused_checkpoint(countdown, check_limits, poll_print)?;
        self.instruction_ip = self.current_frame.ip;
        self.current_frame.ip += 1;
"""
        if op in loads:
            slot = op.removeprefix('LoadLocal')
            if slot:
                vm += f'        self.load_local({slot})?;\n'
            else:
                vm += '        let slot = u16::from(self.current_frame.fetch_u8());\n        self.load_local(slot)?;\n'
        elif op == 'LoadSmallInt':
            vm += (
                '        let value = i64::from(self.current_frame.fetch_i8());\n        self.push(Value::Int(value));\n'
            )
        elif op == 'StoreLocal':
            vm += '        let slot = u16::from(self.current_frame.fetch_u8());\n        self.store_local(slot);\n'
        elif op == 'BinarySubscr':
            vm += """        let index = self.pop();
        let obj = self.pop();
        let result = obj.py_getitem(&index, self);
        obj.drop_with(self);
        index.drop_with(self);
        self.push(result?);
"""
        elif op.startswith('JumpIf'):
            vm += """        let offset = self.current_frame.fetch_i16();
        let cond = self.pop();
        let result = cond.py_bool(self);
        cond.drop_with(self);
"""
            vm += f'        if {"" if op == "JumpIfTrue" else "!"}result? {{\n            jump_relative!(self.current_frame.ip, offset);\n        }}\n'
        else:
            vm += f'        self.{methods[op]}()?;\n'
    vm += '        Ok(())\n    }\n\n'
vm += """    // Charge each constituent instruction so fusion preserves checkpoint cadence.
    #[inline]
    fn fused_checkpoint(&mut self, countdown: &mut u8, check_limits: bool, poll_print: bool) -> RunResult<()> {
        if let Some(c) = countdown.checked_sub(1) {
            *countdown = c;
        } else {
            *countdown = u8::MAX;
            self.dispatch_checkpoint(check_limits, poll_print)?;
        }
        Ok(())
    }
}
"""
(ROOT / 'crates/monty/src/bytecode/vm/fused.rs').write_text(vm)
p = ROOT / 'crates/monty/src/bytecode/vm/mod.rs'
s = p.read_text()
start = '                // BEGIN GENERATED FUSION DISPATCH\n'
end = '                // END GENERATED FUSION DISPATCH\n'
if start in s:
    s = s[: s.index(start)] + s[s.index(end) + len(end) :]
block = start
for i, name in enumerate(names):
    block += f'                #[cfg(feature = "experimental-fusion")]\n                Opcode::{name} => {{\n                    try_catch!(self, self.fused_{i}(&mut countdown, check_limits, poll_print));\n                }}\n'
block += end
s = s.replace('            match opcode {\n', '            match opcode {\n' + block)
p.write_text(s)
print(f'Generated {len(patterns)} fused operations')

# Match the repository formatter without recursively formatting unrelated modules.
subprocess.run(
    [
        'rustfmt',
        '+nightly',
        '--edition',
        '2024',
        '--config',
        'skip_children=true',
        *[str(ROOT / 'crates/monty/src/bytecode' / path) for path in ['op.rs', 'fused.rs', 'vm/fused.rs', 'vm/mod.rs']],
    ],
    check=True,
)
