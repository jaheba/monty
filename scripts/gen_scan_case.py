"""Generate exceptional regex case groups from the target CPython's Unicode tables."""

import sys
import unicodedata
from collections import defaultdict
from pathlib import Path
from re._casefix import _EXTRA_CASES  # pyright: ignore[reportMissingTypeStubs, reportPrivateUsage]

OUT = Path(__file__).parent.parent / 'crates/monty-types/src/scan/case_data.rs'


def main() -> None:
    if unicodedata.unidata_version != '16.0.0':
        raise RuntimeError('Use CPython 3.14 with Unicode 16, matching unicode-general-category')

    parents: dict[int, int] = {}

    def find(value: int) -> int:
        parent = parents.setdefault(value, value)
        if parent != value:
            parents[value] = find(parent)
        return parents[value]

    def union(left: int, right: int) -> None:
        parents[find(left)] = find(right)

    for codepoint in range(sys.maxunicode + 1):
        character = chr(codepoint)
        lower = ord(character.lower()[0])
        if lower != codepoint:
            union(codepoint, lower)

    for lower, equivalents in _EXTRA_CASES.items():
        for equivalent in equivalents:
            union(lower, equivalent)

    groups: dict[int, list[str]] = defaultdict(list)
    for codepoint in sorted(parents):
        groups[find(codepoint)].append(chr(codepoint))

    def simple_upper(character: str) -> str:
        upper = character.upper()
        return upper if len(upper) == 1 else character

    def usual_variants(character: str) -> set[str]:
        lower = character.lower()[0]
        return {character, lower, simple_upper(lower), simple_upper(character).lower()[0]}

    exceptions = [
        group for group in groups.values() if any(not set(group) <= usual_variants(character) for character in group)
    ]
    assert max(map(len, exceptions)) <= 4

    def literal(character: str) -> str:
        return "'\\u{" + f'{ord(character):x}' + "}'"

    lines = [
        f'//! Generated by `scripts/gen_scan_case.py` from CPython {sys.version_info.major}.{sys.version_info.minor}',
        f'//! (Unicode {unicodedata.unidata_version}); do not edit.',
        '',
        '/// Full regex equivalence groups not reachable through ordinary lower/upper pairs.',
        '#[rustfmt::skip]',
        'pub(super) fn variants(character: char) -> Option<[char; 4]> {',
        '    match character {',
    ]
    for group in sorted(exceptions):
        pattern = ' | '.join(map(literal, group))
        values = ', '.join(map(literal, group + [group[0]] * (4 - len(group))))
        lines.append(f'        {pattern} => Some([{values}]),')
    lines.extend(['        _ => None,', '    }', '}', ''])
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text('\n'.join(lines))
    print(f'Wrote {len(exceptions)} exceptional case groups to {OUT}')


if __name__ == '__main__':
    main()
